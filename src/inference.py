from __future__ import annotations
from pathlib import Path
import joblib
import numpy as np
import pandas as pd

MODEL_PATH = Path(__file__).resolve().parents[1] / "models" / "rf_hrv_pipeline.joblib"

def load_model_bundle(path=MODEL_PATH):
    path = Path(path)
    if not path.exists():
        return None, f"Model artifact not found: {path}. Export the fitted model from notebook 05 first."
    try:
        saved = joblib.load(path)
        if isinstance(saved, dict) and "model" in saved:
            model = saved["model"]
            columns = saved.get("feature_columns", getattr(model, "feature_names_in_", None))
            label_map = saved.get("label_map", {
                "0": "Lower dataset risk class (NYHA I/II)",
                "1": "Higher dataset risk class (NYHA III/III-IV)"
            })
        else:
            model = saved
            columns = getattr(model, "feature_names_in_", None)
            label_map = {
                "0": "Lower dataset risk class (NYHA I/II)",
                "1": "Higher dataset risk class (NYHA III/III-IV)"
            }
        if columns is None:
            return None, "Model file has no feature column metadata. Export a bundle with feature_columns."
        return {"model": model, "feature_columns": list(columns), "label_map": label_map}, None
    except Exception as exc:
        return None, f"Could not load model artifact: {exc}"

def predict(bundle, features):
    columns = bundle["feature_columns"]
    missing = [name for name in columns if name not in features]
    if missing:
        raise ValueError(f"Model requires features not generated by the dashboard: {missing}")
    X = pd.DataFrame([[features[c] for c in columns]], columns=columns)
    if not np.isfinite(X.to_numpy(dtype=float)).all():
        raise ValueError("Prediction blocked: feature vector contains NaN or infinity.")
    model = bundle["model"]
    predicted = model.predict(X)[0]
    label = predicted.item() if hasattr(predicted, "item") else predicted
    probability = None
    if hasattr(model, "predict_proba"):
        probs = model.predict_proba(X)[0]
        classes = list(model.classes_)
        if 1 in classes:
            probability = float(probs[classes.index(1)])
    return {
        "label": label,
        "label_text": bundle["label_map"].get(str(label), f"Dataset class {label}"),
        "probability_class_1": probability
    }
